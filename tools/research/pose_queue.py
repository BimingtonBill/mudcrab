#!/usr/bin/env python3
"""The reference-pose pipeline's bookkeeping: grades, the by-hand queue, and merging hand poses.

A reference shot's camera pose is found in three steps (docs/design/reference-pose-pipeline.md):
an automatic ball-park fit, an automatic check that grades each render against its Skyrim
screenshot, and a by-hand fit in the engine for only the shots the check did not accept.

Usage:
    python tools/research/pose_queue.py grade <shot name> <grade> [--by <who>]
    python tools/research/pose_queue.py build
    python tools/research/pose_queue.py merge [--dry-run]
    python tools/research/pose_queue.py status

`grade`  records a verdict in local/reference/pose-grades.json. Grades are research-020's
         vocabulary: `matched` and `close` are accepted, `area only` and `wrong` are queued for
         the by-hand tool, `hand-fit` means the user set it in the engine.
`build`  writes local/reference/manual-queue.json, a shots file of every shot with a reference
         picture whose grade is not accepted (a shot never graded counts as not accepted), minus
         the shots the user flagged with X (local/reference/not-found.jsonl). It also writes
         local/reference/fit-queue.vbs, which opens the engine at the first queued shot; N / B step
         through the rest, P saves.
`merge`  folds local/reference/manual-poses.jsonl into the shots files: the last P per shot
         wins; position, yaw (normalised to 0-360) and pitch are taken, and each shot keeps its
         own hfov, reference, metrics and notes. Merged shots are graded `hand-fit` and the queue
         is rebuilt.
"""

import datetime
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SHOTS_FILES = ["tools/reference/riverwood_shots.json", "tools/reference/uesp_shots_4x3.json"]
LOCAL = os.path.join(ROOT, "local", "reference")
GRADES = os.path.join(LOCAL, "pose-grades.json")
QUEUE = os.path.join(LOCAL, "manual-queue.json")
LAUNCHER = os.path.join(LOCAL, "fit-queue.vbs")
MANUAL = os.path.join(LOCAL, "manual-poses.jsonl")
NOT_FOUND = os.path.join(LOCAL, "not-found.jsonl")
ENGINE = r"C:\Modding\wkj-tools\engine-portal-fit.exe"
ASSETS = r"C:\Modding\SkyrimConverted"
ACCEPTED = {"matched", "close", "hand-fit"}
GRADES_KNOWN = ACCEPTED | {"area only", "wrong"}


def load_json(path, default):
    if not os.path.exists(path):
        return default
    with open(path, encoding="utf-8") as handle:
        return json.load(handle)


def save_json(path, data):
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(data, handle, indent=2, ensure_ascii=False)
        handle.write("\n")


def jsonl(path):
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as handle:
        return [json.loads(line) for line in handle if line.strip()]


def shots_files():
    return [(path, load_json(os.path.join(ROOT, path), None)) for path in SHOTS_FILES]


def grade(name, verdict, by):
    if verdict not in GRADES_KNOWN:
        sys.exit(f"unknown grade {verdict!r}; use one of {sorted(GRADES_KNOWN)}")
    names = {shot["name"] for _, data in shots_files() for shot in data["shots"]}
    if name not in names:
        sys.exit(f"no shot named {name!r} in {SHOTS_FILES}")
    grades = load_json(GRADES, {})
    grades[name] = {"grade": verdict, "by": by, "at": datetime.date.today().isoformat()}
    save_json(GRADES, grades)
    print(f"{name}: {verdict}")


def build():
    grades = load_json(GRADES, {})
    flagged = {record.get("shot") for record in jsonl(NOT_FOUND)}
    queue, size = [], None
    for path, data in shots_files():
        size = size or (data["width"], data["height"])
        if (data["width"], data["height"]) != size:
            sys.exit(f"{path} renders at a different size; the queue needs one size")
        for shot in data["shots"]:
            if not shot.get("reference") or shot["name"] in flagged:
                continue
            if grades.get(shot["name"], {}).get("grade") not in ACCEPTED:
                queue.append(shot)
    save_json(QUEUE, {"width": size[0], "height": size[1], "shots": queue})
    if queue:
        first = queue[0]["name"]
        lines = [
            "' Generated by tools/research/pose_queue.py build: the shots the automatic check did not",
            "' accept. N / B step through them, the Skyrim picture is top-right, P saves, X = can't find it.",
            'Set shell = CreateObject("WScript.Shell")',
            f'shell.CurrentDirectory = "{ROOT}"',
            f'command = "cmd /c ""{ENGINE}"" --assets {ASSETS} " & _',
            f'    "--start-shot local/reference/manual-queue.json {first} " & _',
            '    "> local\\reference\\fit-in-engine.log 2>&1"',
            "shell.Run command, 0, False",
        ]
        with open(LAUNCHER, "w", encoding="utf-8", newline="\r\n") as handle:
            handle.write("\n".join(lines) + "\n")
    elif os.path.exists(LAUNCHER):
        os.remove(LAUNCHER)
    print(f"{len(queue)} shot(s) queued for the by-hand tool" + (f": {LAUNCHER}" if queue else ""))
    for shot in queue:
        print("  ", shot["name"], "-", grades.get(shot["name"], {}).get("grade", "not graded"))


def merge(dry_run):
    latest = {}
    for record in jsonl(MANUAL):
        if record.get("shot"):
            latest[record["shot"]] = record
    grades = load_json(GRADES, {})
    merged = 0
    for path, data in shots_files():
        changed = False
        for shot in data["shots"]:
            record = latest.get(shot["name"])
            if not record:
                continue
            pose = {
                "position": [round(float(value), 1) for value in record["position"]],
                "yaw": round(float(record["yaw"]) % 360.0, 1),
                "pitch": round(float(record["pitch"]), 1),
            }
            for space in ("worldspace_id", "interior_cell_id"):
                if space in record:
                    pose[space] = record[space]
            if all(shot.get(key) == value for key, value in pose.items()):
                continue
            shot.update(pose)
            shot["confidence"] = "hand-fit"
            stamp = f" Pose set by hand in the engine ({str(record.get('saved_at', ''))[:10]})."
            if "Pose set by hand" not in shot.get("note", ""):
                shot["note"] = shot.get("note", "") + stamp
            grades[shot["name"]] = {"grade": "hand-fit", "by": "user", "at": str(record.get("saved_at", ""))[:10]}
            print(f"{shot['name']}: {pose}")
            merged += 1
            changed = True
        if changed and not dry_run:
            save_json(os.path.join(ROOT, path), data)
    if not dry_run:
        save_json(GRADES, grades)
    print(f"{merged} hand pose(s) merged" + (" (dry run)" if dry_run else ""))
    if not dry_run:
        build()


def status():
    grades = load_json(GRADES, {})
    flagged = {record.get("shot") for record in jsonl(NOT_FOUND)}
    counts = {}
    for _, data in shots_files():
        for shot in data["shots"]:
            if not shot.get("reference"):
                verdict = "no reference"
            elif shot["name"] in flagged:
                verdict = "flagged can't-find"
            else:
                verdict = grades.get(shot["name"], {}).get("grade", "not graded")
            counts[verdict] = counts.get(verdict, 0) + 1
    for verdict, count in sorted(counts.items()):
        print(f"{count:3}  {verdict}")


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    command = argv[1]
    if command == "grade" and len(argv) >= 4:
        by = argv[argv.index("--by") + 1] if "--by" in argv else "lead"
        grade(argv[2], argv[3], by)
    elif command == "build":
        build()
    elif command == "merge":
        merge("--dry-run" in argv)
    elif command == "status":
        status()
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
